import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { __unstable__loadDesignSystem, compile } from 'tailwindcss'
import { optimize } from '@tailwindcss/node'
import { loadTailwindStylesheet, tailwindThemeUtilitiesImport } from './tailwind-stylesheet-loader.mjs'

const candidatesOut = process.argv[2] ?? 'test/parity_candidates.official.json'
const parityDataOut = process.argv[3] ?? 'src/core_parity_data.zig'
const roots = (process.env.CALMCSS_TAILWIND_SRC_ROOT ?? '')
  .split(',')
  .map((root) => root.trim())
  .filter(Boolean)

if (roots.length === 0) {
  throw new Error(
    'Set CALMCSS_TAILWIND_SRC_ROOT to one or more Tailwind CSS source roots, for example /path/to/tailwindcss/packages/tailwindcss/src',
  )
}
for (const root of roots) {
  if (!existsSync(root)) throw new Error(`Tailwind source tree not found: ${root}`)
}

const manual = JSON.parse(await readFile('test/parity_candidates.json', 'utf8'))
const candidates = new Set(manual)
for (const root of roots) {
  for (const file of await listTests(root)) {
    const text = await readFile(file, 'utf8')
    for (const block of candidateBlocks(text)) {
      for (const candidate of quotedStrings(block)) {
        if (candidate.length > 0 && candidate.length < 140 && !/[\s{};]/.test(candidate)) {
          candidates.add(candidate)
        }
      }
    }
    for (const candidate of candidateLikeStrings(text)) {
      candidates.add(candidate)
    }
  }
}

const tailwindInput = tailwindThemeUtilitiesImport

const valid = []
const entries = []
for (const candidate of [...candidates].sort()) {
  const tailwind = await compile(tailwindInput, { loadStylesheet: loadTailwindStylesheet })
  const css = optimize(tailwind.build([candidate]), { minify: true })
    .code.replace(/\/\*! tailwindcss[^*]*\*\//g, '')
    .replace(/:root,:host\{[^{}]*\}/g, '')
    .trim()
  if (css.length === 0) continue
  valid.push(candidate)
  entries.push({ candidate, css })
}

const designSystem = await __unstable__loadDesignSystem(tailwindInput, {
  loadStylesheet: loadTailwindStylesheet,
})
const sortRanks = new Map()
for (const [candidate, order] of designSystem.getClassOrder(valid)) {
  if (order !== null) sortRanks.set(candidate, order.toString())
}

await mkdir(dirname(candidatesOut), { recursive: true })
await writeFile(candidatesOut, `${JSON.stringify(valid, null, 2)}\n`)

const candidateBlob = buildBlob(entries.map((entry) => entry.candidate))
const cssTemplates = buildCssTemplates(entries.map((entry) => entry.css))

const parts = [
  '// Generated by scripts/generate-core-parity-data.mjs; do not edit by hand.',
  'const std = @import("std");',
  '',
  'pub const Entry = struct { candidate_start: u32, candidate_len: u16, part_start: u32, part_len: u16, sort_rank: u32 };',
  'const template_ref_mask: u32 = 2147483648;',
  '',
  ...emitBlob('candidate_blob', candidateBlob.lines),
  '',
  ...emitBlob('template_blob', cssTemplates.templateBlob.lines),
  '',
  ...emitBlob('literal_blob', cssTemplates.literalBlob.lines),
  '',
  ...emitIntArray('part_refs', 'u32', cssTemplates.partRefs),
  '',
  ...emitIntArray('part_lens', 'u16', cssTemplates.partLens),
  '',
  'pub const entries = [_]Entry{',
]
for (const [index, entry] of entries.entries()) {
  const sortRank = sortRanks.get(entry.candidate)
  if (sortRank === undefined) throw new Error(`missing sort rank for ${entry.candidate}`)
  const cssRange = cssTemplates.entryRanges[index]
  parts.push(`    .{ .candidate_start = ${candidateBlob.ranges[index].start}, .candidate_len = ${candidateBlob.ranges[index].len}, .part_start = ${cssRange.start}, .part_len = ${cssRange.len}, .sort_rank = ${sortRank} },`)
}
parts.push(
  '};',
  '',
  'pub fn candidate(entry: Entry) []const u8 {',
  '    return candidate_blob[entry.candidate_start .. entry.candidate_start + entry.candidate_len];',
  '}',
  '',
  'pub fn find(name: []const u8) ?Entry {',
  '    var low: usize = 0;',
  '    var high: usize = entries.len;',
  '    while (low < high) {',
  '        const mid = low + (high - low) / 2;',
  '        const entry = entries[mid];',
  '        switch (std.mem.order(u8, name, candidate(entry))) {',
  '            .eq => return entry,',
  '            .lt => high = mid,',
  '            .gt => low = mid + 1,',
  '        }',
  '    }',
  '    return null;',
  '}',
  '',
  'pub fn appendCss(allocator: std.mem.Allocator, out: *std.ArrayList(u8), entry: Entry) !void {',
  '    var index = entry.part_start;',
  '    const end = entry.part_start + entry.part_len;',
  '    while (index < end) : (index += 1) {',
  '        const part_ref = part_refs[index];',
  '        const start = part_ref & ~template_ref_mask;',
  '        const len = part_lens[index];',
  '        const blob = if ((part_ref & template_ref_mask) != 0) template_blob else literal_blob;',
  '        try out.appendSlice(allocator, blob[start .. start + len]);',
  '    }',
  '}',
  '',
)

await mkdir(dirname(parityDataOut), { recursive: true })
await writeFile(parityDataOut, parts.join('\n'))
console.error(`generated ${valid.length} core parity data entries`)

async function listTests(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await listTests(path))
    else if (entry.name.endsWith('.test.ts')) out.push(path)
  }
  return out
}

function candidateBlocks(text) {
  const blocks = []
  for (const re of [/run\(\s*\[([\s\S]*?)\]\s*\)/g, /compileCss\([\s\S]*?,\s*\[([\s\S]*?)\]/g]) {
    for (const match of text.matchAll(re)) blocks.push(match[1])
  }
  return blocks
}

function quotedStrings(text) {
  const out = []
  for (const match of text.matchAll(/(['"])((?:\\.|(?!\1)[^\\\n])*)\1/g)) {
    out.push(match[2].replace(/\\(['"])/g, '$1'))
  }
  return out
}

function candidateLikeStrings(text) {
  const known = new Set([
    'absolute',
    'block',
    'collapse',
    'container',
    'contents',
    'fixed',
    'flex',
    'grid',
    'hidden',
    'inline',
    'invisible',
    'relative',
    'sticky',
    'table',
    'visible',
  ])
  const out = []
  for (const candidate of quotedStrings(text)) {
    if (candidate.length === 0 || candidate.length >= 140) continue
    if (/[\s{};]/.test(candidate)) continue
    if (!/[a-zA-Z]/.test(candidate)) continue
    if (
      !candidate.includes('-') &&
      !candidate.includes(':') &&
      !candidate.includes('[') &&
      !candidate.includes('/') &&
      !candidate.includes('@') &&
      !known.has(candidate)
    ) continue
    if (/^(tailwindcss|@theme|@utility|@variant|https?|\.\/|\.\.|--|[A-Z].*)/.test(candidate)) continue
    if (/\.(css|js|ts|html)$/.test(candidate)) continue
    out.push(candidate)
  }
  return out
}

function buildBlob(values) {
  const ranges = []
  const lines = []
  let offset = 0
  for (const value of values) {
    if (/[\r\n]/.test(value)) throw new Error('compact parity data values must be single-line strings')
    const len = Buffer.byteLength(value, 'utf8')
    ranges.push({ start: offset, len })
    lines.push(value)
    offset += len + 1
  }
  return { ranges, lines }
}

function buildCssTemplates(values) {
  const chunked = values.map(splitTopLevelRules)
  const counts = new Map()
  for (const chunks of chunked) {
    for (const chunk of chunks) counts.set(chunk, (counts.get(chunk) ?? 0) + 1)
  }

  const templateChunks = new Set()
  for (const [chunk, count] of counts) {
    const len = Buffer.byteLength(chunk, 'utf8')
    if (count > 1 && len >= 16 && len * (count - 1) > count * 6) {
      templateChunks.add(chunk)
    }
  }

  const templateRanges = new Map()
  const templateValues = []
  const literalValues = []
  const partRefs = []
  const partLens = []
  const entryRanges = []
  let templateOffset = 0
  let literalOffset = 0
  const templateRefMask = 0x80000000

  for (const chunks of chunked) {
    entryRanges.push({ start: partRefs.length, len: chunks.length })
    for (const chunk of chunks) {
      const len = Buffer.byteLength(chunk, 'utf8')
      if (len > 0xffff) throw new Error(`CSS parity chunk too large for u16: ${len}`)
      if (templateChunks.has(chunk)) {
        let range = templateRanges.get(chunk)
        if (range === undefined) {
          range = { start: templateOffset, len }
          templateRanges.set(chunk, range)
          templateValues.push(chunk)
          templateOffset += len + 1
        }
        partRefs.push(templateRefMask + range.start)
        partLens.push(range.len)
      } else {
        partRefs.push(literalOffset)
        partLens.push(len)
        literalValues.push(chunk)
        literalOffset += len + 1
      }
    }
  }

  return {
    entryRanges,
    partRefs,
    partLens,
    templateBlob: buildBlob(templateValues),
    literalBlob: buildBlob(literalValues),
  }
}

function splitTopLevelRules(css) {
  const chunks = []
  let start = 0
  let depth = 0
  let quote = null
  for (let i = 0; i < css.length; i++) {
    const char = css[i]
    if (quote !== null) {
      if (char === '\\') i++
      else if (char === quote) quote = null
      continue
    }
    if (char === '"' || char === "'") {
      quote = char
    } else if (char === '{') {
      depth++
    } else if (char === '}') {
      depth--
      if (depth === 0) {
        chunks.push(css.slice(start, i + 1))
        start = i + 1
      }
    }
  }
  if (depth !== 0 || quote !== null) return [css]
  if (start < css.length) chunks.push(css.slice(start))
  return chunks
}

function emitBlob(name, lines) {
  if (lines.length === 0) return [`pub const ${name} = "";`]
  return [
    `pub const ${name} =`,
    ...lines.map((line) => `    \\\\${line}`),
    ';',
  ]
}

function emitIntArray(name, type, values) {
  if (values.length === 0) return [`pub const ${name} = [_]${type}{};`]
  const out = [`pub const ${name} = [_]${type}{`]
  for (const value of values) out.push(`    ${value},`)
  out.push('};')
  return out
}
